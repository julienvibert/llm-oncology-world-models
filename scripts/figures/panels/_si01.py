"""One stored course for all three SI1 views (complete path, event ribbon, fingerprint).

Declared selection rule: of the five invasive-ductal-carcinoma courses generated by Kimi K3 in the atlas run
(condition IDC_tumor_only, no clinical conditioning), the course with the longest follow-up. The rule is applied
by code below and asserted against the stored default of the state-map course script. The comparison set of the
fingerprint is every other accepted course of the same run. No model is called; data are stored derivation tables.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "scripts" / "explore"))
sys.path.insert(0, str(ROOT / "scripts"))
import build_trajectory_geometry_gallery_v1 as G  # noqa: E402
import build_paper_individual_state_trajectory_views as V  # noqa: E402

RUN = "kimi_k3_off_full_atlas_n5_complete"
DERIV = ROOT / "runs" / RUN / "derivation"
CONDITION = "IDC_tumor_only"
RULE = ("the longest-followed of the five invasive ductal carcinoma courses generated by Kimi K3 "
        "in the atlas run (no clinical conditioning)")


def _load():
    snaps = pd.read_csv(DERIV / "snapshot_rows.csv", low_memory=False)
    ev = pd.read_csv(DERIV / "event_rows.csv", low_memory=False)
    snaps = snaps[snaps["accepted"].astype(bool)].copy()
    ev = ev[ev["accepted"].astype(bool)].copy()
    snaps["month"] = pd.to_numeric(snaps["days_from_diagnosis"], errors="coerce") / G.MONTH_DAYS
    ev["month"] = pd.to_numeric(ev["days_from_diagnosis"], errors="coerce") / G.MONTH_DAYS
    return G.add_state_coordinates(snaps), ev


def select_id(ev: pd.DataFrame) -> str:
    sub = ev[ev["condition_id"].eq(CONDITION)]
    dur = sub.groupby("trajectory_id")["month"].max()
    return str(dur.idxmax()), int(len(dur))


def load_course() -> tuple[G.Course, str, int]:
    snaps, ev = _load()
    tid, n_pool = select_id(ev)
    assert tid == V.DEFAULT_TRAJECTORY_ID, tid
    cs = snaps[snaps["trajectory_id"].eq(tid)].sort_values(["days_from_diagnosis", "snapshot_index"])
    ce = ev[ev["trajectory_id"].eq(tid)].sort_values(["days_from_diagnosis", "event_index"])
    return G.Course(cs, ce, snaps, ev), tid, n_pool


def baseline_receptors(tid: str) -> dict[str, str]:
    """Receptor status read from the stored baseline biomarker table (not inferred from regimens)."""
    bk = pd.read_csv(DERIV / "baseline_biomarker_rows.csv", low_memory=False)
    bk = bk[bk["trajectory_id"].eq(tid)]
    return dict(zip(bk["biomarker_name"], bk["biomarker_value"].astype(str), strict=True))
