"""Panel si05a_arrow_path: one generated course as four arrows on the frozen state map.

Message: each arrow of the state map is one recorded clinical event; response and progression move
the patient along the disease-burden axis, a side effect or a worse condition along the host axis.
Data: _si05.py (frozen state map, six-model atlas). Generated data only.
Run: uv run python scripts/figures/panels/si05a_arrow_path.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent))
import pandas as pd  # noqa: E402
from matplotlib.colors import LinearSegmentedColormap  # noqa: E402
from matplotlib.lines import Line2D  # noqa: E402
from matplotlib.patches import FancyArrowPatch  # noqa: E402
import _si05 as S  # noqa: E402
from _f3util import axes_mm, new_fig  # noqa: E402
from _si05_style import EVENT_COLOURS  # noqa: E402
from common import INK, save_panel  # noqa: E402

d = S.load()
atlas = pd.read_csv(S.MAP / "state_projection.csv.gz", usecols=["pc1", "pc2"])
A = d["arrows"]
fig = new_fig(70, 70)
ax = axes_mm(fig, 12, 7, 57, 52)
xs = [a["x0"] for a in A] + [a["x1"] for a in A]
ys = [a["y0"] for a in A] + [a["y1"] for a in A]
x0, x1, y0, y1 = min(xs) - 0.07, max(xs) + 0.07, min(ys) - 0.06, max(ys) + 0.07
v = atlas[(atlas.pc1.between(x0, x1)) & (atlas.pc2.between(y0, y1))]
dens = LinearSegmentedColormap.from_list("atlas", ["#FFFFFF", "#FBF3E3", "#F3E3C3", "#E8CF9E"])
ax.hexbin(v.pc1, v.pc2, gridsize=22, extent=(x0, x1, y0, y1), bins="log", cmap=dens, mincnt=1,
          linewidths=0, rasterized=True, zorder=0)
for a in A:
    col = EVENT_COLOURS[a["event"]]
    ax.add_patch(FancyArrowPatch((a["x0"], a["y0"]), (a["x1"], a["y1"]), arrowstyle="-|>", mutation_scale=7,
                                 color=col, lw=1.6, zorder=3, shrinkA=3, shrinkB=3))
    mx, my = (a["x0"] + a["x1"]) / 2, (a["y0"] + a["y1"]) / 2
    n = A.index(a) + 1
    ax.text(mx, my, str(n), fontsize=6, ha="center", va="center", color="white", fontweight="bold", zorder=6,
            bbox=dict(boxstyle="circle,pad=0.25", fc=col, ec="white", lw=0.5))
ax.scatter([A[0]["x0"]], [A[0]["y0"]], s=22, marker="o", facecolor="white", edgecolor=INK, lw=0.8, zorder=5)
ax.scatter([A[-1]["x1"]], [A[-1]["y1"]], s=24, marker="x", color=INK, lw=1.2, zorder=5)
ax.set_xlim(x0, x1)
ax.set_ylim(y0, y1)
ax.set_xticks([])
ax.set_yticks([])
ax.set_xlabel("State-map PC1 (a.u.)")
ax.set_ylabel("State-map PC2 (a.u.)")
h = [Line2D([], [], marker="o", ls="none", mfc="white", mec=INK, ms=4, label="Start of the course"),
     Line2D([], [], marker="x", ls="none", color=INK, ms=4, label=f"End of the record (death, month {d['death_month']:.1f})"),
     Line2D([], [], marker="h", ls="none", mfc="#E8CF9E", mec="none", ms=5, label="Density of all generated patients")]
fig.legend(handles=h, loc="upper left", bbox_to_anchor=(0.02, 1.0), fontsize=6, frameon=False, ncol=1,
           handletextpad=0.3, labelspacing=0.3)
legend = (
    "One generated course as arrows on the state map. Each arrow is one recorded event that changed the "
    "encoded state; the number is the arrow's row in panel b and its colour is the kind of event. Events that "
    "did not change the state (such as the treatment switch) have no arrow. Circle, start of the record; "
    "cross, death. Shading, density of all 105,839 positions of the 4,434 trajectories generated by six models "
    "(log scale), zoomed to the region of this course. The map axes are the first two principal components of "
    "20 encoded tumour-burden and host-condition features, fixed before any analysis. PC1 is loaded mainly by "
    "hepatic tumour burden, disease extent, symptoms and ECOG status; PC2 is loaded mainly by bone-marrow "
    "disease and marrow reserve, against hepatic, thoracic and other-site disease, with symptoms and ECOG status "
    "also contributing. Neither axis is a validated clinical scale and a move along one is not a better or worse "
    "condition (Extended Data Fig. 1). The course is a lung adenocarcinoma generated by "
    "Gemini 3.1 Flash-Lite, chosen by a declared rule (see source). Generated, not a real patient."
)
save_panel(fig, "si05a_arrow_path", legend=legend,
           sources=["outputs/paper_state_map/state_projection.csv.gz", "outputs/paper_state_map/feature_loadings.csv",
                    "scripts/figures/panels/_si05.py"],
           confirm=["Course on the frozen 20-feature state map, so that the axes are the paper's."
                    " Selection rule: LUAD courses of at "
                    "most 10 events where response, toxicity onset and progression each move the patient; the "
                    "lowest SHA-256 of the trajectory id. Only ONE course meets the rule, so no hash selection "
                    "was needed. Gemini 3.1 Flash-Lite model, accepted generated course."],
           message="Each arrow on the state map is one clinical event.")
