"""Panel f6d_precision_ladder: the precision ladder as a narrowing funnel (synthetic atlas).

Message: each added matching criterion shrinks the pool of comparable trajectories, from a median
of 4,433 to 219 to 3; 21.0% of trajectories have no comparator at the finest level (cumulative
ladder; the last rung keeps the primary-site class).
Band height is proportional to log10(median comparable trajectories).

Source: outputs/exploratory_precision_ladder/readout.json (per_rung: median_peers, unanswerable;
n_trajectories). The rung labelled "+ tumour type" in the file is the primary-site class.
Run:  uv run python scripts/figures/panels/f6d_precision_ladder.py
"""
import json
import sys
from pathlib import Path

import matplotlib as mpl
import numpy as np
from matplotlib.patches import Polygon

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common import ROOT, fk, save_panel  # noqa: E402

R = json.loads((ROOT / "outputs" / "exploratory_precision_ladder" / "readout.json").read_text())
rows = R["per_rung"]
NAME = {"everyone": "All\ntrajectories", "+ tumour type": "+ primary-site\nclass", "+ stage": "+ stage",
        "+ molecular driver": "+ molecular\ndriver", "+ baseline state": "+ baseline\ncondition",
        "+ age and sex": "+ age\nand sex", "+ exact histology": "+ exact\nhistology"}
n = len(rows)
cols = mpl.colormaps["viridis"](np.linspace(0.08, 0.92, n))
peers = np.array([r["median_peers"] for r in rows])
assert peers[0] == 4433 and R.get("ladder_definition", "").startswith("cumulative")

W, H = 180.0, 34.0
fig = fk.figure(width=W, height_mm=H)
ax = fig.add_axes([0, 0, 1, 1])
ax.set_xlim(0, W)
ax.set_ylim(0, H)
ax.axis("off")
X0, CW = 33.0, 21.0           # first column left edge, column width (mm)
YC, HMAX = 19.5, 7.0          # funnel centre line and maximum half height (mm)
half = HMAX * np.log10(peers) / np.log10(peers[0])
half = np.maximum(half, 0.9)   # keep the last band visible; value written below
BW = 15.0                       # block width (mm)
for i, r in enumerate(rows):
    cx = X0 + CW * i + CW / 2
    if i < n - 1:   # connecting trapezoid into the next rung, in the colour of the next criterion
        nx = cx + CW
        ax.add_patch(Polygon([(cx + BW / 2, YC + half[i]), (nx - BW / 2, YC + half[i + 1]),
                              (nx - BW / 2, YC - half[i + 1]), (cx + BW / 2, YC - half[i])],
                             closed=True, fc=cols[i + 1], ec="none", alpha=0.35, zorder=1))
    ax.add_patch(Polygon([(cx - BW / 2, YC + half[i]), (cx + BW / 2, YC + half[i]), (cx + BW / 2, YC - half[i]),
                          (cx - BW / 2, YC - half[i])], closed=True, fc=cols[i], ec="none", zorder=2))
    ax.text(cx, H - 0.8, NAME[r["rung"]], fontsize=6, ha="center", va="top", linespacing=1.05)
    ax.text(cx, 8.6, f"{r['median_peers']:,.0f}", fontsize=7, ha="center", va="center", fontweight="bold")
    pct = 100 * r["unanswerable"]
    ax.text(cx, 2.8, f"{pct:.1f}%", fontsize=7, ha="center", va="center", fontweight="bold")
    ax.plot([cx - BW / 2, cx + BW / 2], [7.3, 7.3], color=cols[i], lw=0.0)
ax.text(X0 - 2.0, 8.6, "Median number of\ncomparable trajectories", fontsize=6, ha="right", va="center", linespacing=1.05)
ax.text(X0 - 2.0, 2.8, "Trajectories with no\ncomparator (share of all)", fontsize=6, ha="right", va="center", linespacing=1.05)
ax.text(X0 - 2.0, YC, "Block height\n(log scale)", fontsize=6, ha="right", va="center", linespacing=1.05)

legend = ("Number of comparable trajectories left as an index trajectory of the synthetic atlas is matched on more "
          "characteristics (columns, left to right: all trajectories; then primary-site class; stage; molecular driver; baseline "
          "condition [performance status and disease extent]; age and sex; exact histology [OncoTree code]). Each criterion is "
          "added to those before it. The height of each coloured block is proportional to the logarithm of the median number of "
          "other atlas trajectories in the same cell (written below the block), across the "
          f"{R['n_trajectories']:,} synthetic trajectories of the atlas. Bottom row, share of all {R['n_trajectories']:,} "
          "trajectories with no other trajectory in the same cell (no comparator). Matching uses baseline characteristics only, "
          "not history or treatment, and pools the six models. The atlas was generated by language models; it contains no observed "
          "patients, and the counts describe the generated population, not the ability to validate an individual treatment effect.")
save_panel(fig, "f6d_precision_ladder", legend=legend,
           sources=["outputs/exploratory_precision_ladder/readout.json"],
           confirm=["The last rung keeps primary-site class and adds the exact OncoTree "
                    f"code (cumulative); finest median {peers[-1]:.0f} comparators, no comparator "
                    f"{100 * rows[-1]['unanswerable']:.1f}%.",
                    "Atlas size: n_trajectories = 4,434 in the file, median of 4,433 peers at the top rung (all others).",
                    "Share with no comparator ('unanswerable') is over all 4,434 trajectories.",
                    "The atlas is the six models, pooled.",
                    "Rung 'baseline condition' = ecog_band + extent_band in the file keys.",
                    "Block heights are drawn on a log scale with a minimum height for the last rung (4); a funnel is a design choice, "
                    "the exact values are written below each block."],
           message=f"Each added matching criterion shrinks the comparable pool from 4,433 to {peers[-1]:.0f} (median); "
                   f"{100 * rows[-1]['unanswerable']:.1f}% have none at the finest level.")
