"""Panel f3d_wrong_target: osimertinib without the EGFR target, per model.

Message: without the EGFR target, Sonnet generated short control on osimertinib (median 2.30 months) whereas
Kimi and GLM generated 22.31 and 33.12 months (the five ordering checks are reported in Methods).
Data: medians recomputed from the saved day-level medians (phase1_context_arm_medians.csv of the three
phase-1 runs) at 30.4375 days per month (helper _egfr_days.py); checks passed from
outputs/paper_interventional_trust_map/readout.json (phase1_egfr), built by
scripts/build_paper_interventional_trust_map.py. The trust-map CSV (30.4-day months) is read only to
confirm that the recomputed medians differ from it by the month length alone.
Run: uv run python scripts/figures/panels/f3d_wrong_target.py
"""
import json
import sys
from pathlib import Path

import pandas as pd
from matplotlib.lines import Line2D

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import ROOT, INK, MODEL_COLOURS, save_panel  # noqa: E402
from _f3util import axes_mm, new_fig  # noqa: E402
from _egfr_days import SOURCES as DAY_SOURCES, context_medians, value  # noqa: E402

D = ROOT / "outputs/paper_interventional_trust_map"
g = pd.read_csv(D / "egfr_gate_scores_used.csv").set_index("model")
J = json.loads((D / "readout.json").read_text())["phase1_egfr"]
MED = context_medians()
for col in ("egfr_mut_osi_mo", "egfr_mut_chemo_mo", "egfr_wt_osi_mo", "egfr_wt_chemo_mo"):
    _, st, arm, _ = col.split("_")
    arm = "osimertinib" if arm == "osi" else arm
    for m in g.index:
        assert abs(value(MED, m, st, arm) * 30.4375 / 30.4 - g.loc[m, col]) < 1e-9, (m, col)
models = [("claude_sonnet5", "Sonnet", MODEL_COLOURS["Sonnet"]), ("kimi_k3_off", "Kimi K3", MODEL_COLOURS["Kimi K3"]),
          ("glm52_fp8", "GLM-5.2", MODEL_COLOURS["GLM-5.2"])]
CHECKS = ["egfr_mut_osi_gt_chemo", "egfr_mut_osi_gt_bsc_ttp", "egfr_wt_osi_not_top", "bsc_control",
          "no_impossible_reversal"]
W, H = 119.0, 41.0
fig = new_fig(W, H)
AW, AB, AHt = 46.0, 10.0, 23.5
lefts = [17.0, 70.0]
facets = [("EGFR-mutant", "mut"), ("EGFR wild-type (no target)", "wt")]
axs = []
for k, (lab, st) in enumerate(facets):
    ax = axes_mm(fig, lefts[k], AB, AW, AHt)
    axs.append(ax)
    for i, (m, name, col) in enumerate(models):
        y = len(models) - 1 - i
        o, c = value(MED, m, st, "osimertinib"), value(MED, m, st, "chemo")
        ax.plot([min(o, c), max(o, c)], [y, y], color=col, lw=1.0, alpha=0.45, zorder=1, solid_capstyle="butt")
        ax.plot(c, y, "s", mfc="white", mec=col, mew=1.1, ms=4.2, zorder=2)
        ax.plot(o, y, "o", color=col, ms=5, mec="none", zorder=3)
        ax.text(o + (1.6 if o <= c else -1.6) if False else o, y + 0.3, f"{o:.1f}", ha="center", va="bottom", fontsize=6, color=INK)
    ax.set_xlim(0, 50)
    ax.set_xticks([0, 10, 20, 30, 40, 50])
    ax.set_ylim(-0.55, len(models) - 0.3)
    ax.set_yticks(range(len(models)))
    ax.set_yticklabels([""] * len(models) if k else [n for _, n, _ in models][::-1])
    ax.tick_params(axis="y", length=0)
    ax.set_xlabel("Median first-line PFS (months)")
    ax.text(0.0, 1.0, lab, transform=ax.transAxes, fontsize=7, ha="left", va="bottom")
# colour key for the model rows: short swatch left of each name
for i, (m, name, col) in enumerate(models):
    y = len(models) - 1 - i
    # axes data -> mm: row y sits at AB + (y + 0.55) / (len(models) - 0.3 + 0.55) * AHt
    ymm = AB + (y + 0.55) / (len(models) + 0.25) * AHt
    fig.add_artist(Line2D([0.5 / W, 2.7 / W], [ymm / H] * 2, color=col, lw=2.2))
# marker key (top)
fig.legend(handles=[Line2D([], [], marker="o", ls="", color=INK, ms=5, mec="none", label="Osimertinib"),
                    Line2D([], [], marker="s", ls="", mfc="white", mec=INK, mew=1.1, ms=4.2, label="Chemotherapy")],
           loc="upper left", ncol=2, frameon=False, fontsize=6, handletextpad=0.2, columnspacing=1.0,
           bbox_to_anchor=(69 / W, 1.0 - 0.2 / H))
save_panel(
    fig, "f3d_wrong_target",
    legend=("Median duration of first-line control generated by three models, from the same starting records, for osimertinib "
            "(filled circles, value printed above) and carboplatin-pemetrexed chemotherapy (open squares), in EGFR-mutant (left) "
            "and EGFR wild-type (right) lung cancer. Each model has its own colour. Osimertinib has no target in wild-type "
            "disease, so a short duration is expected: Sonnet generated 2.3 months, whereas Kimi K3 and GLM-5.2 generated 22.3 "
            "and 33.1 months. Each median summarises the generated futures of one arm and status: 45 per arm (15 starting combinations, "
            "three repeats each), except GLM-5.2 chemotherapy, 35 (EGFR-mutant) and 42 (wild-type), where some futures were "
            "not accepted. Futures are not independent patients; no intervals are shown. Months are days / 30.4375."),
    sources=[*DAY_SOURCES, "outputs/paper_interventional_trust_map/egfr_gate_scores_used.csv",
             "outputs/paper_interventional_trust_map/readout.json",
             "scripts/explore/score_interventional_phase1.py (definitions of the five checks)"],
    confirm=["Wild-type osimertinib medians 2.30, 22.31, 33.12 months (days / 30.4375; were 2.30, 22.34, 33.16 at 30.4); "
             "checks 5/5, 5/5, 4/5 match (GLM failed the wild-type check 3).",
             "Check wording taken from scripts/explore/score_interventional_phase1.py (bsc_control: supportive care below the best "
             "active arm in both statuses; no_impossible_reversal: paired gain larger in mutant than wild-type).",
             "n from phase1_context_arm_medians.csv: 45 per arm and status for all three models, except GLM chemotherapy 35 "
             "(mutant) and 42 (wild-type).",
             "Red highlight of the >20-month wild-type values removed (model colours now identify rows); the numbers are printed instead.",
             "Facet headings 'EGFR-mutant' and 'EGFR wild-type (no target)' are used as data labels."],
    message="Without the target, Sonnet gave short control on osimertinib; Kimi and GLM gave 22 and 33 months.")
