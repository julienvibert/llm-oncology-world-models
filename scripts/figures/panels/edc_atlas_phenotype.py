"""Panel edc_atlas_phenotype: patient characteristics and courses by model and OncoTree tissue.

Message: the six models generate different combinations of patient characteristics at diagnosis
and of clinical courses for the same cancer types.
Data: outputs/exploratory_atlas_phenotype_six_model/phenotype_by_tissue_model.csv (from
scripts/explore/build_atlas_phenotype_six_model.py; 4,434 accepted trajectories, 32 OncoTree
tissues, six models).
Run: uv run python scripts/figures/panels/edc_atlas_phenotype.py
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _f2 import axes_mm, canvas  # noqa: E402
from common import INK, MODEL_ORDER, ROOT, save_panel  # noqa: E402
import pandas as pd  # noqa: E402

SRC = ROOT / "outputs" / "exploratory_atlas_phenotype_six_model" / "phenotype_by_tissue_model.csv"
t = pd.read_csv(SRC)
assert set(t["model"]) == set(MODEL_ORDER)

# (column, header, unit for the colour bar, colour map, vmin, vmax)
BASE = [("median_age", "Age", "years", "Blues", 10, 75),
        ("pct_metastatic_or_systemic", "Metastatic\nor systemic", "%", "Blues", 0, 100),
        ("median_baseline_sites", "Disease\nsites", "median", "Blues", 1, 5),
        ("pct_organ_impairment", "Organ\nimpairment", "%", "Blues", 0, 100)]
COURSE = [("median_survival_months", "Survival", "months", "Oranges", 10, 60),
          ("median_lines", "Treatment\nlines", "median", "Oranges", 1, 7),
          ("pct_grade3plus_ae", "Grade ≥3\nadverse event", "%", "Oranges", 0, 100),
          ("pct_new_site", "New disease\nsite", "%", "Oranges", 0, 100)]

order = (t.groupby("tissue")["median_survival_months"].median().sort_values(ascending=False).index)
n_min = t.groupby("tissue")["n"].min()
n_max = t.groupby("tissue")["n"].max()
rows = list(order)
R, C = len(rows), len(MODEL_ORDER)
for col, _h, _u, _c, lo, hi in BASE + COURSE:
    assert t[col].notna().all(), col
    assert lo <= t[col].min() and t[col].max() <= hi, f"{col} outside its colour scale"

W, LABEL, TOP, CELL_H, BLOCK_GAP = 180.0, 37.0, 14.0, 2.9, 3.0
HM_W, GAP = 15.6, 1.8
H_HM = R * CELL_H
BOTTOM = 26.0
H = TOP + H_HM + BOTTOM
fig = canvas(W, H)

x = LABEL
for block, specs in (("At diagnosis", BASE), ("Course after diagnosis", COURSE)):
    x_block = x
    for col, head, unit, cmap, vmin, vmax in specs:
        ax = axes_mm(fig, x, BOTTOM, HM_W, H_HM)
        M = (t.pivot(index="tissue", columns="model", values=col)
             .reindex(index=rows, columns=MODEL_ORDER).to_numpy(float))
        im = ax.imshow(M, cmap=cmap, vmin=vmin, vmax=vmax, aspect="auto", interpolation="nearest")
        ax.set_xticks(range(C))
        ax.set_xticklabels(MODEL_ORDER, rotation=90, fontsize=6)
        ax.set_yticks([])
        ax.tick_params(length=0)
        for s in ax.spines.values():
            s.set_visible(False)
        ax.set_xticks(np.arange(-0.5, C), minor=True)
        ax.set_yticks(np.arange(-0.5, R), minor=True)
        ax.grid(which="minor", color="white", lw=0.4)
        ax.tick_params(which="minor", length=0)
        ax.text(C / 2 - 0.5, -0.9, head, ha="center", va="bottom", fontsize=7, color=INK)
        cax = axes_mm(fig, x + 1.5, 8.0, HM_W - 3.0, 1.6)
        cb = fig.colorbar(im, cax=cax, orientation="horizontal")
        cb.set_ticks([vmin, vmax])
        cb.ax.tick_params(labelsize=6, length=1.5, pad=1)
        cb.outline.set_linewidth(0.3)
        cb.set_label(unit, fontsize=6, labelpad=1)
        x += HM_W + GAP
    fig.text((x_block + x - GAP) / 2 / W, (H - 0.8) / H, block, ha="center", va="top",
             fontsize=7, color=INK)
    x += BLOCK_GAP

lab = axes_mm(fig, 0, BOTTOM, LABEL - 1.0, H_HM)
lab.set_xlim(0, 1)
lab.set_ylim(R - 0.5, -0.5)
lab.axis("off")
for i, tissue in enumerate(rows):
    sparse = n_min[tissue] < 10
    lab.text(0.0, i, tissue, ha="left", va="center", fontsize=7, color=INK)
    n_txt = (f"{int(n_min[tissue])}" if n_min[tissue] == n_max[tissue]
             else f"{int(n_min[tissue])}–{int(n_max[tissue])}")
    lab.text(0.98, i, n_txt + (" *" if sparse else ""), ha="right", va="center", fontsize=7, color=INK)
lab.text(0.98, -0.9, "n per\nmodel", ha="right", va="bottom", fontsize=7, color=INK)

n_traj = int(t["n"].sum())
save_panel(
    fig, "edc_atlas_phenotype",
    legend=(f"Clinical phenotype generated by each model, by OncoTree tissue ({n_traj:,} accepted trajectories, "
            "148 cancer codes, 32 tissues, six models; about five trajectories per code and model). Left block, "
            "at diagnosis: median age; share with metastatic or systemic (haematological) stage; median number of "
            "anatomical disease sites at the first generated assessment; share with any organ impairment (renal, hepatic, cardiac, marrow reserve or pulmonary "
            "function other than normal). Right block, course after diagnosis: median survival from diagnosis (every "
            "trajectory ends in death); median number of systemic treatment lines; share with any adverse event of "
            "grade 3 or higher; share with any new disease site. Each variable has its own colour scale (bar below); "
            "colours are not comparable across variables; every value lies within its scale. n per model, patients per "
            "tissue and model, with the range where models differ; asterisk, fewer than 10 patients per model (one "
            "cancer code). Adverse events and new sites are counted over the whole generated course, so their "
            "frequencies reflect both the generated event patterns and the different survival durations. "
            "Rows ordered by median survival pooled over models. Descriptive, generated data; no real-patient "
            "reference, so the panel does not show which model is realistic."),
    sources=["outputs/exploratory_atlas_phenotype_six_model/phenotype_by_tissue_model.csv"],
    confirm=["Grouping by OncoTree tissue (32) rather than the 8 families of Fig. 2d, to cover all 148 codes.",
             "Rows with 5 patients per model (one code) are shown and marked, not pooled."],
    message="The six models generate different patient characteristics and courses for the same cancers.")
