"""Panel si03a_treatment_journey: how the class of treatment changes from one line to the next.

Message: generated courses follow a recognisable treatment sequence; targeted and endocrine lines are
mostly followed by chemotherapy or immunotherapy-based lines. Built on the six-model atlas
(treatment_rows.csv of the six atlas derivation folders, accepted courses; loader from fig1_data.py,
regimen class from tx_class in atlas_clinical_richness.py). Generated data only.
Run: uv run python scripts/figures/panels/si03a_treatment_journey.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE.parents[1] / "explore" / "figpanels"))
sys.path.insert(0, str(HERE.parents[1] / "explore"))
import numpy as np  # noqa: E402
from _f3util import axes_mm, new_fig  # noqa: E402
from atlas_clinical_richness import tx_class  # noqa: E402
from common import INK, save_panel  # noqa: E402
from fig1_data import _read  # noqa: E402

tr = _read("treatment_rows.csv")
tr["cls"] = tr["component_classes_joined"].map(tx_class)
lines = {g: x.drop_duplicates("line_number").sort_values("line_number")["cls"].tolist()
         for g, x in tr.groupby("_gid")}
classes = ["targeted", "chemo-IO", "IO", "chemo", "endocrine", "other"]
names = ["Targeted", "Chemotherapy +\nimmunotherapy", "Immunotherapy", "Chemotherapy", "Endocrine", "Other"]
short = ["Targeted", "Chemo + IO", "Immunotherapy", "Chemotherapy", "Endocrine", "Other"]
xshort = ["Targeted", "Chemo\n+ IO", "Immuno-\ntherapy", "Chemo-\ntherapy", "Endo-\ncrine", "Other"]
idx = {c: i for i, c in enumerate(classes)}
n_models = tr["model_short"].nunique()

fig = new_fig(180, 72)
mats, ns = [], []
for k, (a, b) in enumerate(((0, 1), (1, 2))):
    M = np.zeros((6, 6))
    for seq in lines.values():
        if len(seq) > b:
            M[idx.get(seq[a], 5), idx.get(seq[b], 5)] += 1
    mats.append(M)
    ns.append(int(M.sum()))
    Mn = M / M.sum(1, keepdims=True).clip(min=1)
    ax = axes_mm(fig, 32 + k * 90, 20, 56, 51)
    im = ax.imshow(Mn, cmap="Blues", vmin=0, vmax=1, aspect="auto")
    ax.set_xticks(range(6), xshort)
    ax.set_yticks(range(6), [f"{s} (n = {int(M[i].sum()):,})" for i, s in enumerate(short)])
    if k == 1:
        ax.set_yticklabels([f"{s} (n = {int(M[i].sum()):,})" for i, s in enumerate(short)])
    ax.tick_params(length=0)
    for sp in ax.spines.values():
        sp.set_visible(False)
    for i in range(6):
        for j in range(6):
            if M[i, j] > 0:
                ax.text(j, i, f"{Mn[i, j]:.0%}", ha="center", va="center", fontsize=6,
                        color="white" if Mn[i, j] > 0.5 else INK)
    nm = (("first", "second"), ("second", "third"))[k]
    ax.set_xlabel(f"Class of the {nm[1]} line", labelpad=1)
    ax.set_ylabel(f"Class of the {nm[0]} line", labelpad=1)
    for e in np.arange(-0.5, 6, 1):
        ax.axvline(e, color="white", lw=0.5)
        ax.axhline(e, color="white", lw=0.5)
cb = fig.colorbar(im, cax=axes_mm(fig, 65, 7.0, 50, 2.2), orientation="horizontal")
cb.set_label("Share of earlier-line courses moving to this class", fontsize=6, labelpad=1)
cb.set_ticks([0, 0.5, 1])
cb.set_ticklabels(["0%", "50%", "100%"])
cb.ax.tick_params(labelsize=6, length=2, width=0.5)
cb.outline.set_linewidth(0.5)
save_panel(
    fig, "si03a_treatment_journey",
    legend=("Treatment sequences in the generated atlas: the class of the next line of therapy, given the class "
            "of the earlier one. Left heatmap, first line to second line (n = " + f"{ns[0]:,}" + " transitions); right heatmap, second line to third "
            "line (n = " + f"{ns[1]:,}" + "). Each row is the class of the earlier line, with the number of "
            "transitions it contains; each cell is the share of those transitions that go to the class named on the "
            "horizontal axis (rows add up to 100%; empty cells, no transitions). Classes: targeted therapy; "
            "chemotherapy with an immune-checkpoint inhibitor; immune-checkpoint inhibitor alone; chemotherapy; "
            "endocrine therapy; other. Courses generated by six models, pooled (accepted courses only; one count "
            "per course reaching that line). Descriptive; not compared with real patients."),
    sources=["runs/*/derivation/treatment_rows.csv for the six atlas runs (loader scripts/explore/figpanels/fig1_data.py)",
             "scripts/explore/atlas_clinical_richness.py (tx_class)"],
    confirm=[f"Six-model atlas ({n_models} models).",
             "Class rules from tx_class (keyword rules); 'other' = anything not matched. Models are pooled; per-model "
             "sequences not shown."],
    message="Generated treatment lines follow a recognisable sequence of drug classes.")
