"""Build the OncoLLM-Atlas OncoTree roster from a raw OncoTree API dump.

Reads (all must exist):
  - data/oncotree/raw/oncotree_2025_10_03.json                  (raw API dump)
  - data/oncotree/raw/oncotree_2025_10_03.fetch_manifest.json   (pin sidecar, fixed at fetch time)
  - data/oncotree/roster_curation_v1.yaml                       (curation overlay; ported from the worksheet)

Writes:
  - data/oncotree/roster_v1.yaml                                (materialized roster, deterministic)

Deterministic by design: no datetime.now() is called anywhere. The build is a
pure function of (raw_json + fetch_manifest + curation_overlay). Rebuilding
without changing inputs produces a byte-identical output.

Overlay schema (v2, locked 2026-05-15)
--------------------------------------
The overlay is generated by `scripts/port_worksheet_to_overlay.py` from the
curation worksheet. Per code:

    tier: primary | secondary | excluded | null
    exclusion_reason: <category> | null         (required iff tier == excluded)
    secondary_role: <role> | null               (required iff tier == secondary)
    primary_non_leaf_rationale: <text> | null   (required iff tier == primary AND non-leaf)
    notes: <text> | null

The legacy `include` field is NOT permitted in the overlay; this script
derives `include` from `tier` for back-compat with downstream consumers:
    tier in {primary, secondary} -> include = True
    tier == excluded             -> include = False
    tier is None                 -> include = None

Re-fetching
-----------
Refreshing the raw OncoTree dump (e.g., to track a new release) is a deliberate
event, not a side effect of building. Run:

    VERSION=oncotree_2025_10_03  # or a newer date-pinned version
    curl -sS "https://oncotree.mskcc.org/api/tumorTypes?version=${VERSION}" \\
         -o "data/oncotree/raw/${VERSION}.json"
    python -c "
    import hashlib, json, datetime as dt
    p = 'data/oncotree/raw/${VERSION}.json'
    sha = hashlib.sha256(open(p,'rb').read()).hexdigest()
    json.dump({
      'alias_used_at_fetch': 'oncotree_latest_stable',
      'resolved_version': '${VERSION}',
      'source_url': 'https://oncotree.mskcc.org/api/tumorTypes?version=${VERSION}',
      'fetched_at': dt.datetime.now(dt.timezone.utc).isoformat(timespec='seconds'),
      'raw_json_path': p,
      'raw_json_sha256': sha,
    }, open(p.replace('.json', '.fetch_manifest.json'), 'w'), indent=2)
    "

Then update the ONCOTREE_VERSION constant in this script and rebuild.

Usage:
    uv run python scripts/build_oncotree_roster.py
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
RAW_DIR = REPO_ROOT / "data" / "oncotree" / "raw"
ROSTER_PATH = REPO_ROOT / "data" / "oncotree" / "roster_v1.yaml"
CURATION_PATH = REPO_ROOT / "data" / "oncotree" / "roster_curation_v1.yaml"

ONCOTREE_VERSION = "oncotree_2025_10_03"
RAW_DUMP = RAW_DIR / f"{ONCOTREE_VERSION}.json"
FETCH_MANIFEST = RAW_DIR / f"{ONCOTREE_VERSION}.fetch_manifest.json"

DEFAULT_EXCLUSION_RULE_CATEGORIES = [
    "non_clinical_grouping_node",
    "pediatric_only_unless_intentional",
    "premalignant_or_in_situ_only_without_invasive_analogue",
    "no_clinical_management_distinction_from_parent",
    "outside_adult_oncology_scope",
]

DEFAULT_TIER_CATEGORIES = ["primary", "secondary", "excluded"]
DEFAULT_SECONDARY_ROLE_CATEGORIES = ["targeted_stress", "pool", "rollup_only", "catalog_only"]

ALLOWED_TIERS: frozenset[str] = frozenset(DEFAULT_TIER_CATEGORIES)
ALLOWED_SECONDARY_ROLES: frozenset[str] = frozenset(DEFAULT_SECONDARY_ROLE_CATEGORIES)


class BuildError(SystemExit):
    """Build-time error with a clear message; aborts the build (fail-fast)."""


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    h.update(path.read_bytes())
    return h.hexdigest()


def _external_refs(row: dict[str, Any]) -> dict[str, list[str]]:
    refs = row.get("externalReferences") or {}
    return {k: list(v) for k, v in refs.items() if v}


def _row_to_entry(row: dict[str, Any]) -> dict[str, Any]:
    return {
        "code": row["code"],
        "name": row["name"],
        "main_type": row.get("mainType"),
        "tissue": row.get("tissue"),
        "parent_code": row.get("parent"),
        "level": row.get("level"),
        "is_leaf": None,
        "external_references": _external_refs(row),
        "tier": None,
        "secondary_role": None,
        "primary_non_leaf_rationale": None,
        "include": None,
        "exclusion_reason": None,
        "curation_notes": None,
    }


def _compute_leaf_status(raw_rows: list[dict[str, Any]]) -> dict[str, bool]:
    """A code is a leaf iff no other row lists it as `parent`."""
    parents: set[str] = set()
    for row in raw_rows:
        parent = row.get("parent")
        if parent:
            parents.add(parent)
    return {row["code"]: row["code"] not in parents for row in raw_rows}


def _load_pin_manifest() -> dict[str, Any]:
    if not FETCH_MANIFEST.exists():
        raise BuildError(
            f"Pin manifest not found at {FETCH_MANIFEST}. "
            "See the 'Re-fetching' section in this script for how to create one."
        )
    pin = json.loads(FETCH_MANIFEST.read_text())
    required = {"alias_used_at_fetch", "resolved_version", "source_url", "fetched_at", "raw_json_sha256"}
    missing = required - set(pin)
    if missing:
        raise BuildError(f"Pin manifest at {FETCH_MANIFEST} is missing required fields: {sorted(missing)}")
    if pin["resolved_version"] != ONCOTREE_VERSION:
        raise BuildError(
            f"Pin manifest resolved_version={pin['resolved_version']!r} does not match "
            f"script ONCOTREE_VERSION={ONCOTREE_VERSION!r}. Update one or the other."
        )
    return pin


def _verify_raw_sha(pin: dict[str, Any]) -> None:
    actual = _sha256(RAW_DUMP)
    expected = pin["raw_json_sha256"]
    if actual != expected:
        raise BuildError(
            f"SHA-256 mismatch on {RAW_DUMP}.\n"
            f"  manifest expects: {expected}\n"
            f"  actual:           {actual}\n"
            "The raw dump has changed since the manifest was written. "
            "Either restore the original raw, or refresh the manifest (see 'Re-fetching')."
        )


def _load_curation() -> dict[str, Any]:
    if not CURATION_PATH.exists():
        return {
            "codes": {},
            "exclusion_rule_categories": DEFAULT_EXCLUSION_RULE_CATEGORIES,
            "tier_categories": DEFAULT_TIER_CATEGORIES,
            "secondary_role_categories": DEFAULT_SECONDARY_ROLE_CATEGORIES,
        }
    with CURATION_PATH.open() as f:
        data = yaml.safe_load(f) or {}
    data.setdefault("codes", {})
    data.setdefault("exclusion_rule_categories", DEFAULT_EXCLUSION_RULE_CATEGORIES)
    data.setdefault("tier_categories", DEFAULT_TIER_CATEGORIES)
    data.setdefault("secondary_role_categories", DEFAULT_SECONDARY_ROLE_CATEGORIES)
    return data


def _validate_overlay(
    curation: dict[str, Any],
    known_codes: set[str],
    leaf_status: dict[str, bool],
) -> None:
    """Fail-fast overlay validation against the tier-based schema.

    Enforces (all hard failures):
      * tier in {primary, secondary, excluded, null}
      * exclusion_reason set iff tier == "excluded" (and within allowed categories)
      * secondary_role set iff tier == "secondary" (and within allowed roles)
      * primary_non_leaf_rationale set iff tier == "primary" AND node is non-leaf
        (and is then a non-empty string)
      * tier == null pending state requires all other curation fields null
      * legacy `include` field is NOT permitted (single source of truth = tier)
      * code must exist in the OncoTree dump
    """
    allowed_reasons = set(curation["exclusion_rule_categories"])
    codes_overlay: dict[str, Any] = curation["codes"]

    unknown = sorted(set(codes_overlay) - known_codes)
    if unknown:
        raise BuildError(
            f"Curation overlay references {len(unknown)} unknown OncoTree code(s): "
            f"{unknown[:10]}{'...' if len(unknown) > 10 else ''}. "
            f"Typo? Or a code removed in a newer OncoTree version?"
        )

    errors: list[str] = []
    for code, entry in codes_overlay.items():
        if not isinstance(entry, dict):
            errors.append(f"{code}: overlay entry must be a mapping, got {type(entry).__name__}")
            continue
        if "include" in entry:
            errors.append(
                f"{code}: legacy 'include' field is not permitted in the overlay "
                "(tier is the single source of truth; build derives include automatically)"
            )
            continue

        tier = entry.get("tier")
        excl = entry.get("exclusion_reason")
        role = entry.get("secondary_role")
        rat = entry.get("primary_non_leaf_rationale")
        notes = entry.get("notes")

        if tier not in ALLOWED_TIERS and tier is not None:
            errors.append(
                f"{code}: tier={tier!r} not in {sorted(ALLOWED_TIERS)} (or null)"
            )
            continue

        if tier == "excluded":
            if excl is None:
                errors.append(f"{code}: tier=excluded requires a non-null exclusion_reason")
            elif excl not in allowed_reasons:
                errors.append(
                    f"{code}: exclusion_reason={excl!r} not in allowed categories "
                    f"({sorted(allowed_reasons)})"
                )
            if role is not None:
                errors.append(f"{code}: tier=excluded must have secondary_role=null (got {role!r})")
            if rat is not None:
                errors.append(
                    f"{code}: tier=excluded must have primary_non_leaf_rationale=null"
                )
        elif tier == "secondary":
            if excl is not None:
                errors.append(
                    f"{code}: tier=secondary must have exclusion_reason=null (got {excl!r})"
                )
            if role is None:
                errors.append(f"{code}: tier=secondary requires a non-null secondary_role")
            elif role not in ALLOWED_SECONDARY_ROLES:
                errors.append(
                    f"{code}: secondary_role={role!r} not in allowed roles "
                    f"({sorted(ALLOWED_SECONDARY_ROLES)})"
                )
            if rat is not None:
                errors.append(
                    f"{code}: tier=secondary must have primary_non_leaf_rationale=null"
                )
        elif tier == "primary":
            if excl is not None:
                errors.append(
                    f"{code}: tier=primary must have exclusion_reason=null (got {excl!r})"
                )
            if role is not None:
                errors.append(f"{code}: tier=primary must have secondary_role=null (got {role!r})")
            is_leaf = leaf_status.get(code)
            if is_leaf is None:
                errors.append(f"{code}: leaf status unknown (code missing from raw dump?)")
            elif is_leaf:
                if rat is not None:
                    errors.append(
                        f"{code}: tier=primary AND leaf must have primary_non_leaf_rationale=null"
                    )
            else:
                if not (isinstance(rat, str) and rat.strip()):
                    errors.append(
                        f"{code}: tier=primary AND non-leaf requires a non-empty "
                        "primary_non_leaf_rationale (documented-exception rule)"
                    )
        elif tier is None:
            if any(x is not None for x in (excl, role, rat)):
                errors.append(
                    f"{code}: tier=null (pending) must have all curation fields null"
                )

        if notes is not None and not isinstance(notes, str):
            errors.append(
                f"{code}: notes must be a string or null (got {type(notes).__name__})"
            )

    if errors:
        joined = "\n  - ".join(errors[:20])
        more = f"\n  ... and {len(errors) - 20} more" if len(errors) > 20 else ""
        raise BuildError(f"Curation overlay validation failed:\n  - {joined}{more}")


def _derive_include(tier: str | None) -> bool | None:
    if tier in ("primary", "secondary"):
        return True
    if tier == "excluded":
        return False
    return None


def _merge_curation(
    entries: list[dict[str, Any]], curation: dict[str, Any]
) -> dict[str, dict[str, int]]:
    codes_overlay = curation["codes"]
    tier_counts = {"primary": 0, "secondary": 0, "excluded": 0, "null": 0}
    role_counts = {"targeted_stress": 0, "pool": 0, "rollup_only": 0, "catalog_only": 0}
    include_counts = {"include_true": 0, "include_false": 0, "include_null_pending": 0}

    for e in entries:
        ov = codes_overlay.get(e["code"])
        if ov is not None:
            e["tier"] = ov.get("tier")
            e["secondary_role"] = ov.get("secondary_role")
            e["primary_non_leaf_rationale"] = ov.get("primary_non_leaf_rationale")
            e["exclusion_reason"] = ov.get("exclusion_reason")
            e["curation_notes"] = ov.get("notes")
        e["include"] = _derive_include(e["tier"])

        tier_counts[e["tier"] if e["tier"] is not None else "null"] += 1
        if e["tier"] == "secondary" and e["secondary_role"] in role_counts:
            role_counts[e["secondary_role"]] += 1
        if e["include"] is True:
            include_counts["include_true"] += 1
        elif e["include"] is False:
            include_counts["include_false"] += 1
        else:
            include_counts["include_null_pending"] += 1

    return {"tier": tier_counts, "secondary_role": role_counts, "include": include_counts}


def build_roster() -> dict[str, Any]:
    pin = _load_pin_manifest()
    _verify_raw_sha(pin)

    raw = json.loads(RAW_DUMP.read_text())
    leaf_status = _compute_leaf_status(raw)
    entries = [_row_to_entry(r) for r in raw]
    for e in entries:
        e["is_leaf"] = leaf_status[e["code"]]
    entries.sort(key=lambda e: (e["level"] or 0, e["code"]))
    known_codes = {e["code"] for e in entries}

    curation = _load_curation()
    _validate_overlay(curation, known_codes, leaf_status)
    stats = _merge_curation(entries, curation)

    by_level: dict[int, int] = {}
    for e in entries:
        lvl = e["level"] or 0
        by_level[lvl] = by_level.get(lvl, 0) + 1

    return {
        "schema_version": "oncotree_roster_v1",
        "oncotree_pin": {
            "alias_used_at_fetch": pin["alias_used_at_fetch"],
            "resolved_version": pin["resolved_version"],
            "source_url": pin["source_url"],
            "fetched_at": pin["fetched_at"],
            "raw_json_path": pin.get("raw_json_path", str(RAW_DUMP.relative_to(REPO_ROOT))),
            "raw_json_sha256": pin["raw_json_sha256"],
        },
        "total_nodes": len(entries),
        "nodes_by_level": dict(sorted(by_level.items())),
        "curation_overlay": {
            "path": str(CURATION_PATH.relative_to(REPO_ROOT)),
            "tier_counts": {
                "primary": stats["tier"]["primary"],
                "secondary": stats["tier"]["secondary"],
                "excluded": stats["tier"]["excluded"],
                "null_pending": stats["tier"]["null"],
            },
            "secondary_role_counts": dict(stats["secondary_role"]),
            "include_true": stats["include"]["include_true"],
            "include_false": stats["include"]["include_false"],
            "include_null_pending": stats["include"]["include_null_pending"],
        },
        "exclusion_rule_categories": list(curation["exclusion_rule_categories"]),
        "tier_categories": list(curation.get("tier_categories", DEFAULT_TIER_CATEGORIES)),
        "secondary_role_categories": list(
            curation.get("secondary_role_categories", DEFAULT_SECONDARY_ROLE_CATEGORIES)
        ),
        "nodes": entries,
    }


def main() -> None:
    if not RAW_DUMP.exists():
        raise BuildError(
            f"Raw OncoTree dump not found at {RAW_DUMP}. "
            "See the 'Re-fetching' section in this script."
        )

    roster = build_roster()
    ROSTER_PATH.parent.mkdir(parents=True, exist_ok=True)
    with ROSTER_PATH.open("w") as f:
        yaml.safe_dump(roster, f, sort_keys=False, allow_unicode=True, width=120)

    pin = roster["oncotree_pin"]
    ov = roster["curation_overlay"]
    tc = ov["tier_counts"]
    rc = ov["secondary_role_counts"]
    print(f"Wrote {ROSTER_PATH.relative_to(REPO_ROOT)}")
    print(f"  resolved_version: {pin['resolved_version']} (via alias {pin['alias_used_at_fetch']})")
    print(f"  fetched_at:       {pin['fetched_at']}")
    print(f"  raw_json_sha256:  {pin['raw_json_sha256']}")
    print(f"  total_nodes:      {roster['total_nodes']}")
    print(f"  by_level:         {roster['nodes_by_level']}")
    print(f"  tier:             primary={tc['primary']}  secondary={tc['secondary']}  "
          f"excluded={tc['excluded']}  pending={tc['null_pending']}")
    print(f"  secondary_role:   targeted_stress={rc['targeted_stress']}  pool={rc['pool']}  "
          f"rollup_only={rc['rollup_only']}  catalog_only={rc['catalog_only']}")
    print(f"  include:          true={ov['include_true']}  false={ov['include_false']}  "
          f"pending={ov['include_null_pending']}")


if __name__ == "__main__":
    main()
