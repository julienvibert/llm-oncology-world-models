"""Port the curation worksheet into the build-script-consumed overlay.

Reads:
  - data/oncotree/curation_worksheet_v1.yaml     (curated worksheet)

Writes:
  - data/oncotree/roster_curation_v1.yaml        (populated overlay)

The worksheet is the clinician-facing curation file (grouped by main_type,
carries mechanical pre-fills + advisory `suggested_*` fields). The overlay is
the machine-consumed input to `scripts/build_oncotree_roster.py` (flat codes
map, only the curation fields).

This adapter is the bridge between the two. It is:

  - Pure: depends only on the worksheet content; no external state.
  - Deterministic: codes emitted in alphabetical order; field order fixed.
  - Idempotent: running twice produces byte-identical output.

Fields ported per code (worksheet -> overlay):

  tier                          -> tier
  exclusion_reason              -> exclusion_reason
  secondary_role                -> secondary_role
  primary_non_leaf_rationale    -> primary_non_leaf_rationale
  notes                         -> notes

Dropped (mechanical / curator-facing only):

  code, name, level, parent, is_leaf, main_type,
  suggested_tier, suggested_exclusion_reason.

The overlay's `codes:` map is sorted alphabetically by code; within each
entry the field order is locked (tier, exclusion_reason, secondary_role,
primary_non_leaf_rationale, notes) for stable diffs.

Usage:
    uv run python scripts/port_worksheet_to_overlay.py
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
WORKSHEET_PATH = REPO_ROOT / "data" / "oncotree" / "curation_worksheet_v1.yaml"
OVERLAY_PATH = REPO_ROOT / "data" / "oncotree" / "roster_curation_v1.yaml"


ALLOWED_TIERS: frozenset[str] = frozenset({"primary", "secondary", "excluded"})
ALLOWED_SECONDARY_ROLES: frozenset[str] = frozenset(
    {"targeted_stress", "pool", "rollup_only", "catalog_only"}
)
ALLOWED_EXCLUSION_REASONS: frozenset[str] = frozenset(
    {
        "non_clinical_grouping_node",
        "pediatric_only_unless_intentional",
        "premalignant_or_in_situ_only_without_invasive_analogue",
        "no_clinical_management_distinction_from_parent",
        "outside_adult_oncology_scope",
    }
)

# The overlay header is written from scratch each port. Embedding it here keeps
# the adapter authoritative over the file's docs — the schema described below
# is exactly what _validate_overlay in build_oncotree_roster.py enforces.
OVERLAY_HEADER = """\
# OncoTree curation overlay for OncoLLM-Atlas
#
# Generated by scripts/port_worksheet_to_overlay.py from
# data/oncotree/curation_worksheet_v1.yaml. Do not hand-edit; re-run the
# adapter after editing the worksheet.
#
# Consumed by scripts/build_oncotree_roster.py to materialize
# data/oncotree/roster_v1.yaml.
#
# Tier semantics (curation rules, 2026-05-14):
#   primary    - clinically meaningful entities for headline atlas analysis.
#                BY DEFAULT leaf-only. Non-leaf primary entries require a
#                non-empty primary_non_leaf_rationale string (documented-
#                exception rule for canonical headline entities like CCRCC,
#                DLBCLNOS, FL, MCL, CML, HL whose OncoTree children are rare
#                variants rather than co-equal subtypes).
#   secondary  - valid but rare, redundant, ultra-specific, or
#                taxonomy-heavy labels; retained for stress / sensitivity
#                analyses, not headline tables. Stratified by secondary_role.
#   excluded   - grouping nodes, benign/premalignant-only without an
#                invasive analogue, pediatric-only unless intentional,
#                outside adult oncology scope, or no distinct management
#                signal from parent.
#
# Secondary roles (only meaningful when tier == "secondary"):
#   targeted_stress  - deliberately sampled in the stress/sensitivity panel.
#   pool             - eligible for stratified random sampling against a
#                      per-stratum budget.
#   rollup_only      - useful taxonomy umbrella; pooled-level claims roll up
#                      from leaf-tier results. Not sampled.
#   catalog_only     - documented for completeness; not generated.
#   Generation-eligibility: only {targeted_stress, pool} reach the runner.
#
# Pediatric / AYA entities are INCLUDED by default (curation rule, 2026-05-13:
# no limit on patient age in scope). Use pediatric_only_unless_intentional only
# when intentionally dropping a specific pediatric-only entity.
#
# Per-code schema (overlay v2, locked 2026-05-15):
#   <CODE>:
#     tier: primary | secondary | excluded | null
#     exclusion_reason: <one of the exclusion_rule_categories below, or null>
#                       Required iff tier == "excluded"; null otherwise.
#     secondary_role: targeted_stress | pool | rollup_only | catalog_only | null
#                     Required iff tier == "secondary"; null otherwise.
#     primary_non_leaf_rationale: <free text, or null>
#                     Required iff tier == "primary" AND the node is non-leaf
#                     in OncoTree. Null on any other configuration. Documents
#                     the clinical reason a non-leaf node is treated as a
#                     headline primary entity.
#     notes: <free text, or null>
#                     Optional rationale for the methods section. Carries
#                     through to roster_v1.yaml.
#
# Legacy `include` field is NOT permitted in this overlay; the build script
# derives include from tier (primary|secondary -> True; excluded -> False;
# null -> None) for back-compat with downstream consumers.
#
# After editing the worksheet, run:
#   uv run python scripts/port_worksheet_to_overlay.py
#   uv run python scripts/build_oncotree_roster.py

"""


class PortError(SystemExit):
    """Adapter error with a clear message; aborts the port (fail-fast)."""


def _validate_node(node: dict[str, Any]) -> list[str]:
    """Return a list of error strings for this node; empty if valid."""
    errors: list[str] = []
    code = node.get("code", "<missing>")

    tier = node.get("tier")
    if tier not in ALLOWED_TIERS and tier is not None:
        errors.append(f"{code}: tier={tier!r} not in {sorted(ALLOWED_TIERS)}")
        return errors  # downstream checks depend on tier

    is_leaf = node.get("is_leaf")
    if not isinstance(is_leaf, bool):
        errors.append(f"{code}: is_leaf must be a bool in the worksheet")
        return errors

    excl = node.get("exclusion_reason")
    role = node.get("secondary_role")
    rat = node.get("primary_non_leaf_rationale")

    if tier == "excluded":
        if excl not in ALLOWED_EXCLUSION_REASONS:
            errors.append(
                f"{code}: tier=excluded requires exclusion_reason in "
                f"{sorted(ALLOWED_EXCLUSION_REASONS)} (got {excl!r})"
            )
        if role is not None:
            errors.append(f"{code}: tier=excluded must have secondary_role=null (got {role!r})")
        if rat is not None:
            errors.append(
                f"{code}: tier=excluded must have primary_non_leaf_rationale=null (got non-null)"
            )
    elif tier == "secondary":
        if excl is not None:
            errors.append(f"{code}: tier=secondary must have exclusion_reason=null (got {excl!r})")
        if role not in ALLOWED_SECONDARY_ROLES:
            errors.append(
                f"{code}: tier=secondary requires secondary_role in "
                f"{sorted(ALLOWED_SECONDARY_ROLES)} (got {role!r})"
            )
        if rat is not None:
            errors.append(
                f"{code}: tier=secondary must have primary_non_leaf_rationale=null (got non-null)"
            )
    elif tier == "primary":
        if excl is not None:
            errors.append(f"{code}: tier=primary must have exclusion_reason=null (got {excl!r})")
        if role is not None:
            errors.append(f"{code}: tier=primary must have secondary_role=null (got {role!r})")
        if is_leaf:
            if rat is not None:
                errors.append(
                    f"{code}: tier=primary AND leaf must have primary_non_leaf_rationale=null"
                )
        else:
            if not (isinstance(rat, str) and rat.strip()):
                errors.append(
                    f"{code}: tier=primary AND non-leaf requires a non-empty "
                    "primary_non_leaf_rationale (documented-exception rule)"
                )
    elif tier is None:
        if any(x is not None for x in (excl, role, rat)):
            errors.append(
                f"{code}: tier=null (pending) must have all curation fields null"
            )

    notes = node.get("notes")
    if notes is not None and not isinstance(notes, str):
        errors.append(f"{code}: notes must be a string or null (got {type(notes).__name__})")

    return errors


def _build_entry(node: dict[str, Any]) -> dict[str, Any]:
    """Build the overlay entry for one node, with locked field order."""
    return {
        "tier": node.get("tier"),
        "exclusion_reason": node.get("exclusion_reason"),
        "secondary_role": node.get("secondary_role"),
        "primary_non_leaf_rationale": node.get("primary_non_leaf_rationale"),
        "notes": node.get("notes"),
    }


def port(worksheet: dict[str, Any]) -> dict[str, Any]:
    """Pure transform: worksheet dict -> overlay dict. Validates fail-fast.

    Codes are emitted alphabetically; per-entry field order is locked.
    """
    errors: list[str] = []
    entries: dict[str, dict[str, Any]] = {}

    seen: set[str] = set()
    for group in worksheet.get("groups", []):
        for node in group.get("nodes", []):
            code = node.get("code")
            if not isinstance(code, str) or not code:
                errors.append(f"<group {group.get('main_type')!r}>: node missing code")
                continue
            if code in seen:
                errors.append(f"{code}: duplicate code across worksheet groups")
                continue
            seen.add(code)

            node_errors = _validate_node(node)
            errors.extend(node_errors)
            if node_errors:
                continue
            entries[code] = _build_entry(node)

    if errors:
        joined = "\n  - ".join(errors[:30])
        more = f"\n  ... and {len(errors) - 30} more" if len(errors) > 30 else ""
        raise PortError(f"Worksheet validation failed:\n  - {joined}{more}")

    ordered_codes = {code: entries[code] for code in sorted(entries)}

    return {
        "schema_version": "oncotree_curation_v2",
        "tier_categories": ["primary", "secondary", "excluded"],
        "secondary_role_categories": ["targeted_stress", "pool", "rollup_only", "catalog_only"],
        "exclusion_rule_categories": [
            "non_clinical_grouping_node",
            "pediatric_only_unless_intentional",
            "premalignant_or_in_situ_only_without_invasive_analogue",
            "no_clinical_management_distinction_from_parent",
            "outside_adult_oncology_scope",
        ],
        "codes": ordered_codes,
    }


def serialize(overlay: dict[str, Any]) -> str:
    """Render the overlay to YAML with the header docstring prepended."""
    body = yaml.safe_dump(
        overlay,
        sort_keys=False,
        allow_unicode=True,
        width=1000,
        default_flow_style=False,
    )
    return OVERLAY_HEADER + body


def main() -> None:
    if not WORKSHEET_PATH.exists():
        raise PortError(f"Worksheet not found at {WORKSHEET_PATH}")

    worksheet = yaml.safe_load(WORKSHEET_PATH.read_text())
    overlay = port(worksheet)
    text = serialize(overlay)
    OVERLAY_PATH.write_text(text)

    counts = {"primary": 0, "secondary": 0, "excluded": 0, "null": 0}
    roles = {"targeted_stress": 0, "pool": 0, "rollup_only": 0, "catalog_only": 0}
    for entry in overlay["codes"].values():
        tier = entry["tier"]
        counts[tier if tier is not None else "null"] += 1
        if tier == "secondary":
            roles[entry["secondary_role"]] += 1

    print(f"Wrote {OVERLAY_PATH.relative_to(REPO_ROOT)}")
    print(f"  total codes:      {len(overlay['codes'])}")
    print(f"  tier counts:      primary={counts['primary']}  "
          f"secondary={counts['secondary']}  excluded={counts['excluded']}  "
          f"null={counts['null']}")
    print(f"  secondary roles:  targeted_stress={roles['targeted_stress']}  "
          f"pool={roles['pool']}  rollup_only={roles['rollup_only']}  "
          f"catalog_only={roles['catalog_only']}")


if __name__ == "__main__":
    main()
